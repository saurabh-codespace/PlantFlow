CREATE TABLE vehicle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    type VARCHAR(10) NOT NULL CHECK (type IN ('BUGGY','VAN','BUS')),
    capacity INTEGER NOT NULL CHECK (capacity BETWEEN 1 AND 60),
    status VARCHAR(15) NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE','MAINTENANCE'))
);
CREATE TABLE driver (
    username VARCHAR(100) PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);
CREATE TABLE allocation (
    trip_id BIGINT PRIMARY KEY,
    vehicle_id BIGINT NOT NULL UNIQUE REFERENCES vehicle(id),
    driver_id VARCHAR(100) NOT NULL UNIQUE REFERENCES driver(username)
);
CREATE TABLE trip_assignment (
    trip_id BIGINT PRIMARY KEY,
    request_version BIGINT NOT NULL DEFAULT 0,
    terminal_version BIGINT NOT NULL DEFAULT 0,
    decision VARCHAR(10),
    reason VARCHAR(200)
);
CREATE TABLE fleet_state (
    id INTEGER PRIMARY KEY CHECK (id=1),
    version BIGINT NOT NULL
);
