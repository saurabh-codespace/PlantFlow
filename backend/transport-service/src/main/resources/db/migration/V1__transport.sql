CREATE TABLE location (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name VARCHAR(100) NOT NULL UNIQUE,
 zone VARCHAR(60) NOT NULL,x INTEGER NOT NULL,y INTEGER NOT NULL
);
CREATE TABLE trip (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 kind VARCHAR(20) NOT NULL CHECK(kind IN ('ON_DEMAND','SHUTTLE')),
 origin_id BIGINT NOT NULL REFERENCES location(id),destination_id BIGINT NOT NULL REFERENCES location(id),
 requested_by VARCHAR(100) NOT NULL,purpose VARCHAR(200) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN ('REQUESTED','ASSIGNING','ASSIGNED','ARRIVED','IN_PROGRESS','COMPLETED','CANCELLED')),
 vehicle_id BIGINT,vehicle_label VARCHAR(30),capacity INTEGER,driver_id VARCHAR(100),driver_name VARCHAR(100),
 scheduled_at TIMESTAMP WITH TIME ZONE,created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 assigned_at TIMESTAMP WITH TIME ZONE,arrived_at TIMESTAMP WITH TIME ZONE,started_at TIMESTAMP WITH TIME ZONE,completed_at TIMESTAMP WITH TIME ZONE,
 version BIGINT NOT NULL DEFAULT 0,assignment_version BIGINT,assignment_error VARCHAR(300),
 CHECK(origin_id <> destination_id)
);
CREATE INDEX trip_owner ON trip(requested_by,created_at);
CREATE INDEX trip_driver ON trip(driver_id,status);
CREATE TABLE reservation (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 trip_id BIGINT NOT NULL REFERENCES trip(id),username VARCHAR(100) NOT NULL,
 seats INTEGER NOT NULL CHECK(seats BETWEEN 1 AND 40),UNIQUE(trip_id,username)
);
